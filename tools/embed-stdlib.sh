# Print src/stdlib/embedded.c: the standard modules written in Plumlang
# (src/stdlib/plum/*.plum), built into the plum binary so `seed net.http`
# needs no files. A module's name is its file name with '_' as '.':
# net_http.plum is net.http. The text goes in as bytes, since MSVC limits
# how long a string literal may be.
#
# Usage: sh tools/embed-stdlib.sh > src/stdlib/embedded.c   (make stdlib-embed)
dir=${1:-src/stdlib/plum}
echo "/* SPDX-License-Identifier: Apache-2.0 OR LicenseRef-Plumlang-Commercial-1.0 */"
echo "/* Generated by tools/embed-stdlib.sh from src/stdlib/plum; don't edit. */"
echo '#include "stdlib/embedded.h"'
echo
i=0
for f in $(ls "$dir"/*.plum | sort); do
    echo "static const char source_$i[] = {"
    # every byte, then 16 to a line: the same on every od (BSD's lays out its
    # lines differently from GNU's)
    od -An -v -tx1 "$f" | awk '
        { for (k = 1; k <= NF; k++) bytes[n++] = tolower($k) }
        END {
            for (i = 0; i < n; i += 16) {
                line = "   "
                for (k = i; k < i + 16 && k < n; k++) line = line " 0x" bytes[k] ","
                print line
            }
        }'
    echo "    0x00,"
    echo "};"
    echo
    i=$((i + 1))
done
echo "static const PlumEmbeddedModule modules[] = {"
i=0
for f in $(ls "$dir"/*.plum | sort); do
    name=$(basename "$f" .plum | tr '_' '.')
    echo "    {\"$name\", source_$i, sizeof source_$i - 1},"
    i=$((i + 1))
done
echo "};"
echo
echo "const PlumEmbeddedModule *plum_embedded_module(const char *name) {"
echo "    for (size_t i = 0; i < sizeof modules / sizeof modules[0]; i++) {"
echo "        if (strcmp(modules[i].name, name) == 0) {"
echo "            return &modules[i];"
echo "        }"
echo "    }"
echo "    return NULL;"
echo "}"
echo
echo "const PlumEmbeddedModule *plum_embedded_module_at(size_t i) {"
echo "    return i < sizeof modules / sizeof modules[0] ? &modules[i] : NULL;"
echo "}"
